"""2D editor -> 3D conformer -> optional force-field relaxation -> XYZ / SDF."""
import io
import re

import streamlit as st
from rdkit import Chem
from rdkit.Chem import AllChem
from streamlit_ketcher import st_ketcher

from molecule_viewer import render_molecule_viewer


def build_3d(smiles: str, optimize: bool, max_iterations: int = 250):
    """Return a molecule and a result description. No user-supplied code is executed."""
    if not smiles or not smiles.strip():
        raise ValueError('Draw a molecule first.')
    if len(smiles) > 8000:
        raise ValueError('Molecule is too large for the quick builder.')
    molecule = Chem.MolFromSmiles(smiles)
    if molecule is None:
        raise ValueError('The drawing could not be parsed. Check the structure, charges, and bonds.')
    if molecule.GetNumHeavyAtoms() > 125:
        raise ValueError('Quick builder supports up to 125 heavy atoms.')
    molecule = Chem.AddHs(molecule)
    if molecule.GetNumAtoms() > 300:
        raise ValueError('Quick builder supports up to 300 total atoms.')
    params = AllChem.ETKDGv3()
    params.randomSeed = 42
    params.maxIterations = 80
    status = AllChem.EmbedMolecule(molecule, params)
    if status != 0:
        raise ValueError('3D embedding failed. Try a smaller molecule or a different stereochemical drawing.')
    note = '3D coordinates generated using ETKDG (not optimized).'
    if optimize:
        if AllChem.MMFFHasAllMoleculeParams(molecule):
            props = AllChem.MMFFGetMoleculeProperties(molecule, mmffVariant='MMFF94')
            ff = AllChem.MMFFGetMoleculeForceField(molecule, props)
            method = 'MMFF94'
        elif AllChem.UFFHasAllMoleculeParams(molecule):
            ff = AllChem.UFFGetMoleculeForceField(molecule)
            method = 'UFF'
        else:
            raise ValueError('No compatible MMFF94 or UFF atom parameters for this molecule. Try generating without optimization.')
        if ff is None:
            raise ValueError('Failed to initialize molecular mechanics force field.')
        result = ff.Minimize(maxIts=max_iterations)
        energy = ff.CalcEnergy()
        note = f'{method} relaxation: {"converged" if result == 0 else "iteration limit reached"}; energy {energy:.3f} kcal/mol (force-field energy).'
    return molecule, note


def to_xyz(molecule):
    conf = molecule.GetConformer()
    lines = [str(molecule.GetNumAtoms()), 'Generated by Bridges-2 Molecule Builder (RDKit)']
    for atom in molecule.GetAtoms():
        p = conf.GetAtomPosition(atom.GetIdx())
        lines.append(f'{atom.GetSymbol():<2} {p.x: .8f} {p.y: .8f} {p.z: .8f}')
    return '\n'.join(lines) + '\n'


def to_sdf(molecule):
    stream = io.StringIO()
    writer = Chem.SDWriter(stream)
    writer.write(molecule)
    writer.flush()
    writer.close()
    return stream.getvalue()


def molecule_builder_page(sftp_connection, checked_new_path, checked_remote_path, safe_child, show_error):
    st.title('🧪 Molecule Builder')
    st.caption('Draw in 2D, generate a 3D conformer, optionally relax the geometry, then save an XYZ or SDF to your Bridges-2 workspace.')
    try:
        smiles = st_ketcher(st.session_state.get('builder_initial_smiles', ''), key='molecule_builder_canvas', height=430)
    except Exception as exc:
        st.error(f'The 2D editor could not load: {exc}')
        return
    c1, c2, c3 = st.columns([1.5, 1.2, 2])
    with c1:
        optimize = st.checkbox('Quick optimize (MMFF94 / UFF)', value=True)
    with c2:
        iterations = st.selectbox('Max iterations', [100, 250, 500], index=1)
    with c3:
        st.caption('A single starting conformer is generated. For complex or flexible structures, geometry and stereochemistry require validation.')
    if st.button('Generate 3D molecule', type='primary', use_container_width=True):
        try:
            molecule, note = build_3d(smiles, optimize, iterations)
            st.session_state.builder_xyz = to_xyz(molecule)
            st.session_state.builder_sdf = to_sdf(molecule)
            st.session_state.builder_note = note
            st.session_state.builder_smiles = Chem.MolToSmiles(Chem.RemoveHs(molecule), isomericSmiles=True)
        except Exception as exc:
            st.session_state.pop('builder_xyz', None)
            st.session_state.pop('builder_sdf', None)
            st.error(str(exc))

    if 'builder_xyz' not in st.session_state:
        return
    st.success(st.session_state.builder_note)
    st.code(st.session_state.builder_smiles, language=None)
    render_molecule_viewer(st.session_state.builder_sdf, 'builder_result.sdf')
    d1, d2 = st.columns(2)
    with d1:
        st.download_button('⬇ Download XYZ', st.session_state.builder_xyz, file_name='molecule.xyz', mime='chemical/x-xyz', use_container_width=True)
    with d2:
        st.download_button('⬇ Download SDF', st.session_state.builder_sdf, file_name='molecule.sdf', mime='chemical/x-mdl-sdfile', use_container_width=True)

    st.subheader('Save to Bridges-2')
    st.caption('Files are saved in the current folder. Existing files will not be overwritten.')
    name_col, format_col = st.columns([3, 1])
    with name_col:
        filename = st.text_input('File name (without extension)', value='molecule', key='builder_filename')
    with format_col:
        fmt = st.selectbox('Format', ['XYZ', 'SDF'], key='builder_file_format')
    if st.button('💾 Save in current folder', type='primary'):
        try:
            if not re.fullmatch(r'[a-zA-Z0-9][a-zA-Z0-9._-]{0,95}', filename) or filename in ('.', '..'):
                raise ValueError('Use 1–96 characters: letters, numbers, periods, underscores, or hyphens.')
            target = safe_child(st.session_state.current, filename + '.' + fmt.lower())
            contents = st.session_state.builder_xyz if fmt == 'XYZ' else st.session_state.builder_sdf
            ssh, sftp = sftp_connection()
            try:
                checked_remote_path(sftp, st.session_state.current)
                checked_new_path(sftp, target)
                try:
                    sftp.lstat(target)
                except IOError as err:
                    if getattr(err, 'errno', None) != 2:
                        raise
                else:
                    raise FileExistsError('A file with this name already exists. Choose a different name.')
                with sftp.open(target, 'xb') as output:
                    output.write(contents.encode('utf-8'))
            finally:
                sftp.close()
                ssh.close()
            st.success(f'Saved {filename}.{fmt.lower()} in your current folder.')
        except Exception as exc:
            show_error(exc)
